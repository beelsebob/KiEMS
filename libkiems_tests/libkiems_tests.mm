- (void)testExteriorGridPaddingCannotRedensifyAwayFromCutBoard {
    // The input deliberately contains bad pre-existing exterior lines whose cells shrink again
    // toward the artificial domain boundaries. Rebuilding must discard them and produce a strictly
    // outward-growing transition from the sliced board [0,3].
    const auto rebuilt = kiems::grid_detail::rebuildExteriorPadding(
        {-8, -7, -3, 0, 1, 2, 3, 7, 8}, 0, 3, -6, 9, 4, 2, 0.1);
    const std::vector<double> expected = {-6, -2, 0, 1, 2, 3, 5, 9};
    XCTAssertEqual(rebuilt, expected);

    // Walking out from either board edge, widths may grow or stay constant, never shrink.
    double previous = rebuilt[3] - rebuilt[2];
    for (std::size_t i = 2; i > 0; --i) {
        const double width = rebuilt[i] - rebuilt[i - 1];
        XCTAssertGreaterThanOrEqual(width, previous);
        previous = width;
    }
    previous = rebuilt[5] - rebuilt[4];
    for (std::size_t i = 5; i + 1 < rebuilt.size(); ++i) {
        const double width = rebuilt[i + 1] - rebuilt[i];
        XCTAssertGreaterThanOrEqual(width, previous);
        previous = width;
    }
}

