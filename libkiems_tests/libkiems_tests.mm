double firstAreaExcessExpectedArea() {
    const Cu::Polygon groundTruthOuter = pathFromLiteral(
        "{1898704,425118}{1899959,425118}{1900146,425156}{1900215,425184}{1900480,425449}{1900482,425453}"
        "{1900509,425518}{1900546,425706}{1900546,426924}{1900397,426841}{1898975,425928}{1898813,425820}"
        "{1897977,425207}{1898171,425082}{1898251,425066}{1898443,425066}");
    return std::abs(Cu::signedArea(groundTruthOuter));
}

// Runs the captured calls' outer+holes through the current triangulator in order, one call at a time
// (a fresh solution vector each time, exactly like Cu::triangulate() itself does), and returns the
// total triangle area of only the *last* call's result -- the "did state from earlier calls corrupt
// this one" signal the bisection test below is probing for.
double triangulateLastCallArea(const std::vector<TriangulateCall>& sequence) {
    std::vector<Cu::Triangle> solution;
    for (const auto& call : sequence) {
        Cu::PolygonSet raw;
        raw.reserve(call.holes.size() + 1);
        raw.push_back(call.outer);
        raw.insert(raw.end(), call.holes.begin(), call.holes.end());
        solution = Cu::triangulate(raw, 0.0, call.label);
    }
    return totalArea(solution);
}

