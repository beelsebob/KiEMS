// Outer loops use positive signed area regardless of which order looks natural to write.
Cu::Polygon rectPolygon(double x0, double y0, double x1, double y1) {
    Cu::Polygon path = {{x0, y0}, {x0, y1}, {x1, y1}, {x1, y0}};
    if (Cu::signedArea(path) < 0) {
        std::reverse(path.begin(), path.end());
    }
    return path;
}

void unionInto(const Cu::PolygonSet& paths, Cu::PolygonSet& tree) {
    tree = Cu::unionPolygons(paths);
}

double triangleArea(const Cu::Triangle& t) {
    return std::abs((t.b.x() - t.a.x()) * (t.c.y() - t.a.y()) - (t.c.x() - t.a.x()) * (t.b.y() - t.a.y())) / 2.0;
}

double totalArea(const std::vector<Cu::Triangle>& triangles) {
    double sum = 0;
    for (const Cu::Triangle& t : triangles) {
        sum += triangleArea(t);
    }
    return sum;
}

// NPTHHole/ViaHole are Hole subclasses (see importer.hpp) -- no longer aggregates, so built by
// field assignment rather than brace-init the way board_slicing.cpp/importer.cpp themselves do.
kiems::NPTHHole npthAtMm(double xMm, double yMm, double diameterMm) {
    kiems::NPTHHole hole;
    hole.x1 = hole.x2 = xMm * kSimUnitsPerMm;
    hole.y1 = hole.y2 = yMm * kSimUnitsPerMm;
    hole.diameter = diameterMm * kSimUnitsPerMm;
    return hole;
}

