- (void)testUniformGridChirpZTransformMatchesDirectDFT {
    constexpr std::size_t sampleCount = 257;
    constexpr std::size_t frequencyCount = 13;
    constexpr double dt = 2.75e-12;
    constexpr double timeStart = dt;
    constexpr double frequencyStart = 1.13e9;
    constexpr double frequencyStep = 73.25e6;

    std::vector<double> time(sampleCount);
    std::vector<double> samples(sampleCount);
    for (std::size_t n = 0; n < sampleCount; ++n) {
        time[n] = timeStart + static_cast<double>(n) * dt;
        samples[n] = 0.7 * std::sin(2.0 * M_PI * 1.41e9 * time[n]) +
                     0.2 * std::cos(2.0 * M_PI * 2.03e9 * time[n]);
    }
    std::vector<double> frequencies(frequencyCount);
    for (std::size_t k = 0; k < frequencyCount; ++k) {
        frequencies[k] = frequencyStart + static_cast<double>(k) * frequencyStep;
    }

    const auto actual = kiems::dftTimeToFreq(time, samples, frequencies, "pulse");
    XCTAssertTrue(actual.has_value());
    if (!actual) return;

    for (std::size_t k = 0; k < frequencyCount; ++k) {
        std::complex<double> expected(0.0, 0.0);
        for (std::size_t n = 0; n < sampleCount; ++n) {
            expected += samples[n] *
                        std::exp(std::complex<double>(0.0, -2.0 * M_PI * frequencies[k] * time[n]));
        }
        expected *= 2.0 * dt;
        const double tolerance = std::max(1e-18, std::abs(expected) * 2e-10);
        XCTAssertEqualWithAccuracy((*actual)[k].real(), expected.real(), tolerance);
        XCTAssertEqualWithAccuracy((*actual)[k].imag(), expected.imag(), tolerance);
    }
}

