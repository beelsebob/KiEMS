- (void)testTriangulateCallHistoryReplayReproducesFirstAreaExcessOfARun {
    // A second, independent capture of the same real board's front solder mask (layer 0) run, taken
    // after _dumpAllTriangulateCalls() was fixed to only log calls since the last dump (previously it
    // re-dumped the whole accumulated history on every anomaly, making later captures full of
    // duplicates -- see the doc comment on testTriangulateCallHistoryReplayReproducesAreaExcess above).
    // This capture is the very first anomaly of a fresh run: only 3 Triangulate() calls total, all of
    // them present here (see firstAreaExcessCalls()), giving a complete, minimal reproduction rather
    // than a prefix of a longer one. The first two calls are identical to calls -6/-5/-4 above (same
    // giant outer + hole0, same 10-vertex and 6-vertex regions), confirming both captures start the
    // same real board slice the same way.
    //
    // RESOLVED (see testBisectFirstAreaExcessAnomalyToFindTheCulpritPriorCall and the doc comment on
    // testTriangulateCallHistoryReplayReproducesAreaExcess above): Triangulate() is correct here too --
    // firstAreaExcessExpectedArea() is the area of a *different*, un-simplified 16-vertex polygon, not
    // the 6-vertex one actually triangulated below. The fix belongs in Cu::triangulate()'s own
