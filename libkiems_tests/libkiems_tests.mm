// 1mm == 10000 simulation units (constants::unitMultiplier / (1000 * constants::baseUnit) -- see
// board_slicing.cpp's own _mmToSimUnits()). sliceBoardForSimulation() expects hullPadding()/
// viaEdgeDistance()/viaSpacing() already in this space (normally EMSConfig::
// scaledToSimulationUnits()'s job) -- tests set them directly rather than pulling in the whole
// config-scaling pipeline just to get there.
constexpr double kSimUnitsPerMm = 10000.0;

libkicad::PolygonLoop rectMm(double x0, double y0, double x1, double y1) {
    libkicad::PolygonLoop loop;
    loop.pointsMm = {{x0, y0}, {x1, y0}, {x1, y1}, {x0, y1}};
    return loop;
}

libkicad::CopperPolygon copperRectMm(const std::string& net, const std::string& layer, double x0,
                                                   double y0, double x1, double y1) {
    libkicad::CopperPolygon polygon;
    polygon.netName = net;
    polygon.copperLayerName = layer;
    polygon.loop = rectMm(x0, y0, x1, y1);
    return polygon;
}

// Parses the "{{x,y},{x,y},...}" text polygon_geometry.cpp's own regression-dump log lines print, so
// a real board's captured coordinates can be pasted in verbatim (copy/paste from a log line) rather
// than hand-transcribed into a C++ initializer list -- transcribing hundreds of coordinates by hand
// is exactly the kind of thing that silently introduces the bug you're trying to reproduce. Ignores
// all punctuation and just extracts every (possibly-negative) integer token in order, pairing them up
// -- robust to exactly where braces/commas land, which matters here since the literal below got
// manually re-wrapped across many string-literal lines when pasted in.
Cu::Polygon pathFromLiteral(const std::string& literal) {
    std::vector<std::int64_t> numbers;
    std::size_t i = 0;
    while (i < literal.size()) {
        const bool isSignStart = literal[i] == '-' && i + 1 < literal.size() && std::isdigit(static_cast<unsigned char>(literal[i + 1]));
        if (std::isdigit(static_cast<unsigned char>(literal[i])) || isSignStart) {
            std::size_t j = i + 1;
            while (j < literal.size() && std::isdigit(static_cast<unsigned char>(literal[j]))) {
                ++j;
            }
            numbers.push_back(std::stoll(literal.substr(i, j - i)));
            i = j;
        } else {
            ++i;
        }
    }
    Cu::Polygon path;
    path.reserve(numbers.size() / 2);
    for (std::size_t n = 0; n + 1 < numbers.size(); n += 2) {
        path.emplace_back(numbers[n], numbers[n + 1]);
    }
    return path;
}

