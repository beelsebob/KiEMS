- (void)testEyeDiagramIdentityChannel {
    constexpr std::size_t frequencyCount = 129;
    std::vector<double> frequencies(frequencyCount);
    std::vector<std::complex<double>> transfer(frequencyCount, {1.0, 0.0});
    for (std::size_t index = 0; index < frequencyCount; ++index) {
        frequencies[index] = static_cast<double>(index) * 4e9 / static_cast<double>(frequencyCount - 1);
    }

    const auto first = kiems::computeEyeDiagram(frequencies, transfer, 1e9);
    const auto second = kiems::computeEyeDiagram(frequencies, transfer, 1e9);
    XCTAssertTrue(first.has_value());
    XCTAssertTrue(second.has_value());
    if (!first.has_value() || !second.has_value()) {
        return;
    }

    XCTAssertEqual(first->bitRate, 1e9);
    XCTAssertEqual(first->timeUI.size(), static_cast<std::size_t>(65));
    XCTAssertEqualWithAccuracy(first->timeUI.front(), -0.5, 1e-12);
    XCTAssertEqualWithAccuracy(first->timeUI.back(), 1.5, 1e-12);
    XCTAssertFalse(first->traces.empty());
    XCTAssertTrue(first->traces == second->traces);
    std::array<std::size_t, 8> threeBitPatternCounts{};
    for (const auto& trace : first->traces) {
        XCTAssertEqual(trace.size(), first->timeUI.size());
        XCTAssertTrue(std::all_of(trace.begin(), trace.end(), [](double value) { return std::isfinite(value); }));

        // Sample halfway through the preceding, central, and following bit. An eye made only from
        // transition-centred slices can look plausible while silently omitting the flat and
        // single-edge histories; an identity channel must retain every three-bit PRBS7 pattern.
        const unsigned preceding = trace[8] >= 0 ? 1U : 0U;  // -0.25 UI
        const unsigned central = trace[32] >= 0 ? 1U : 0U;  //  0.50 UI
        const unsigned following = trace[56] >= 0 ? 1U : 0U; //  1.25 UI
        ++threeBitPatternCounts[(preceding << 2U) | (central << 1U) | following];
    }
    XCTAssertTrue(std::all_of(threeBitPatternCounts.begin(), threeBitPatternCounts.end(),
                              [](std::size_t count) { return count > 0; }));
    const auto [leastCommon, mostCommon] =
        std::minmax_element(threeBitPatternCounts.begin(), threeBitPatternCounts.end());
    XCTAssertLessThanOrEqual(*mostCommon - *leastCommon, static_cast<std::size_t>(1));
}

- (void)testEyeDiagramDelayedChannelSweptAboveDC {
    // A lossless 150 ps delay sampled only from 1 to 10 GHz, like a typical simulation sweep.
    // Holding the 1 GHz complex value below the sweep used to close this eye to ~30%.
    constexpr std::size_t frequencyCount = 1001;
    constexpr double delay = 150e-12;
    std::vector<double> frequencies(frequencyCount);
    std::vector<std::complex<double>> transfer(frequencyCount);
    for (std::size_t index = 0; index < frequencyCount; ++index) {
        frequencies[index] = 1e9 + static_cast<double>(index) * 9e9 / static_cast<double>(frequencyCount - 1);
        transfer[index] = std::polar(1.0, -2.0 * M_PI * frequencies[index] * delay);
    }

    const auto eye = kiems::computeEyeDiagram(frequencies, transfer, 5e9);
    XCTAssertTrue(eye.has_value());
    if (!eye.has_value()) {
        return;
    }
    // Inner opening (half the gap between the lowest "1" and highest "0") at the best sample phase.
    double innerOpening = -std::numeric_limits<double>::infinity();
    for (std::size_t sample = 0; sample < eye->timeUI.size(); ++sample) {
        double lowestOne = std::numeric_limits<double>::infinity();
        double highestZero = -std::numeric_limits<double>::infinity();
        for (const auto& trace : eye->traces) {
            if (trace[sample] >= 0) {
                lowestOne = std::min(lowestOne, trace[sample]);
            } else {
                highestZero = std::max(highestZero, trace[sample]);
            }
        }
        innerOpening = std::max(innerOpening, 0.5 * (lowestOne - highestZero));
    }
    XCTAssertGreaterThan(innerOpening, 0.9);
}

