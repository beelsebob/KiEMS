- (void)testPlaceStitchingViasRejectsAnnularRingIntersectionsWithNonGroundTraces {
    const Cu::PolygonSet cutout = {rectPolygon(0, 0, 40000, 40000)};
    const Cu::PolygonSet boardOutline = {rectPolygon(-200000, -200000, 200000, 200000)};
    const kiems::SlicingConfig slicing{
        .viaEdgeDistance = 2000.0,
        .viaSpacing = 10000.0,
        .platingThickness = 50,
        .stitchingViaHoleDiameter = 300,
        .stitchingViaAnnularRingDiameter = 600,
        .viaClearance = 200,
    };
    std::vector<Cu::PolygonSet> groundPerLayer(1);
    unionInto(cutout, groundPerLayer[0]);

    const kiems::StitchingViaPlacement baseline =
        kiems::placeStitchingVias(slicing, cutout, boardOutline, groundPerLayer, {}, {});
    XCTAssertFalse(baseline.vias.empty());
    if (baseline.vias.empty()) {
        return;
    }

    // A narrow routed trace crosses the first candidate's annular ring without containing its
    // centre, exercising disc/polygon intersection rather than a centre-point-only check.
    const double x = baseline.vias.front().x;
    const double y = baseline.vias.front().y;
    std::vector<Cu::PolygonSet> nonGroundTracesPerLayer(1);
    unionInto({rectPolygon(x + 250, y - 1000, x + 500, y + 1000)}, nonGroundTracesPerLayer[0]);
    const kiems::StitchingViaPlacement blocked = kiems::placeStitchingVias(
        slicing, cutout, boardOutline, groundPerLayer, nonGroundTracesPerLayer, {});

    // The total can legitimately stay the same: freeing the blocked slot can let a candidate that
    // was previously too close to it be placed instead. What must hold is that the blocked position
    // is rejected and no placed via's annular ring overlaps the trace.
    const double ringRadius = slicing.stitchingViaAnnularRingDiameter / 2;
    XCTAssertTrue(std::any_of(blocked.failedAttempts.begin(), blocked.failedAttempts.end(), [&](const auto& attempt) {
        return std::hypot(attempt.x() - x, attempt.y() - y) < 1.0;
    }));
    for (const auto& via : blocked.vias) {
        const double dx = std::max({x + 250 - via.x, 0.0, via.x - (x + 500)});
        const double dy = std::max({y - 1000 - via.y, 0.0, via.y - (y + 1000)});
        XCTAssertGreaterThan(std::hypot(dx, dy), ringRadius);
    }
}

