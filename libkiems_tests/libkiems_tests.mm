- (void)testBisectFirstAreaExcessAnomalyToFindTheCulpritPriorCall {
    // firstAreaExcessCalls() has 3 real Triangulate() calls: call 1 (giant outer + hole0), call 2
    // (10-vertex), call 3 (6-vertex, whose result is the one that's "wrong" in production). Replaying
    // all 3 in order reproduces the exact real "wrong" area (confirmed by
    // testTriangulateCallHistoryReplayReproducesFirstAreaExcessOfARun). This test asked *why*: is call 3
    // wrong only because of what came immediately before it, does it need both prior calls or just one,
    // does call order matter, and is a single prior call enough regardless of which one (a generic "Nth
    // call is broken" bug) or does it have to be these specific polygons?
    //
    // ANSWER (from variant A below): call 3, run completely alone with *zero* prior Triangulate() calls,
    // already produces that same "wrong" area -- there is no prior-call dependency at all, ruling out
    // every cross-call state-leak variant this test was built to distinguish between in one shot.
    // firstAreaExcessExpectedArea() itself turned out to be the area of a different (un-simplified)
    // polygon than the one being triangulated, not a value Triangulate() was ever failing to reach --
    // see testTriangulateCallHistoryReplayReproducesFirstAreaExcessOfARun's own doc comment for the full
    // resolution and where the real bug (a false positive in Cu::triangulate()'s own area-conservation
    // check) actually was. Nothing here is a correctness assertion on the library -- every variant just
    // logs its own triangulated area next to the same fixed (and, per the above, not truly "expected")
    // value so the pattern across variants can be read from the console.
    const std::vector<TriangulateCall> all = firstAreaExcessCalls();
    const double expected = firstAreaExcessExpectedArea();
    NSLog(@"Bisection target: call 3 alone should triangulate to expected=%f", expected);

    auto logVariant = [&](const char* variantName, const std::vector<TriangulateCall>& sequence) {
        const double area = triangulateLastCallArea(sequence);
        NSLog(@"variant '%s' (%lu call(s)) -> area %f, expected %f, diff %f, %s", variantName,
              (unsigned long)sequence.size(), area, expected, area - expected,
              (std::abs(area - expected) <= expected * 0.001) ? "OK" : "WRONG");
    };

    // A: call 3 with nothing before it at all.
    logVariant("A: [3]", {all[2]});
    // B: call 3 preceded only by call 1 (the giant outer + hole0).
    logVariant("B: [1, 3]", {all[0], all[2]});
    // C: call 3 preceded only by call 2 (the 10-vertex region).
    logVariant("C: [2, 3]", {all[1], all[2]});
    // D: the real, full sequence (known to reproduce the anomaly).
    logVariant("D: [1, 2, 3]", {all[0], all[1], all[2]});
    // E: same 3 calls, but 1 and 2 swapped -- does order matter, or just which calls happened before?
    logVariant("E: [2, 1, 3]", {all[1], all[0], all[2]});
    // F: call 3 preceded by two calls to itself -- does *any* two prior Triangulate() calls corrupt the
    // third, even with no other polygon involved at all?
    logVariant("F: [3, 3, 3]", {all[2], all[2], all[2]});
    // G: call 3 preceded by one call to itself -- does even a single prior call, of any polygon, corrupt
    // the next one?
    logVariant("G: [3, 3]", {all[2], all[2]});
    // H: call 2 alone, to confirm call 2's own result is correct in isolation (a sanity check that the
    // "wrongness" is specific to call 3's position in the sequence, not to call 2's polygon itself).
    {
        Cu::PolygonSet raw = {all[1].outer};
        const std::vector<Cu::Triangle> solution = Cu::triangulate(raw, 0.0, "history-call-2");
        const double call2Area = totalArea(solution);
        const double call2Expected = std::abs(Cu::signedArea(all[1].outer));
        NSLog(@"variant 'H: [2] alone' -> area %f, expected %f (own outer's own area, no separate ground "
              @"truth captured), diff %f",
              call2Area, call2Expected, call2Area - call2Expected);
    }
}

