- (void)testTriangulateRealBoardOuterFindsExcessThresholdCount {
    // A live-run bisection on this exact outer+92-holes region hit its own "neither half alone
    // reproduces it, but the whole does" fallback immediately at the top level (46-vs-46 split) --
    // i.e. the excess isn't concentrated in any contiguous chunk of holes, only some larger combined
    // count triggers it. Binary-searching *how many* of the real holes (in their original order) are
    // needed together, entirely offline against the real captured data, finds that threshold directly
    // instead of guessing at another log round-trip.
    const Cu::Polygon outer = realBoardMaskOuter();
    const std::vector<Cu::Polygon> holes = realBoardMaskHoles();
    XCTAssertEqual(holes.size(), static_cast<std::size_t>(92));

    auto excessForFirstN = [&](std::size_t n) -> double {
        Cu::PolygonSet raw;
        raw.reserve(n + 1);
        raw.push_back(outer);
        double expected = std::abs(Cu::signedArea(outer));
        for (std::size_t i = 0; i < n; ++i) {
            raw.push_back(holes[i]);
            expected -= std::abs(Cu::signedArea(holes[i]));
        }
        const std::vector<Cu::Triangle> solution = Cu::triangulate(raw, 0.0, "real-board-hole-prefix");
        if (solution.empty()) {
            NSLog(@"n=%lu: triangulation failed", (unsigned long)n);
            return -1.0;
        }
        const double area = totalArea(solution);
        const double diff = area - expected;
        NSLog(@"n=%lu holes: triangulated=%f expected=%f diff=%f", (unsigned long)n, area, expected, diff);
        return diff;
    };

    for (std::size_t n : {1u, 2u, 4u, 8u, 16u, 23u, 32u, 46u, 64u, 80u, 92u}) {
        excessForFirstN(n);
    }
}

